def main():
    ids = []
    with open(IN) as f:
        header = f.readline()
        for line in f:
            line = line.strip()
            if not line:
                continue
            ids.append(line.split(" ", 1)[0])
    n = 0
    with open(OUT, "w") as out:
        out.write("pathway\tscore\n")
        for g in ids:
            s = S.get(g, 1)
            out.write(f"{g}\t{s}\n")
            n += 1
    unknown = [k for k in S if k not in set(ids)]
    print("rows", n, "listed-but-absent", len(unknown), unknown[:20], file=sys.stderr)
    from collections import Counter
    print(Counter(S.get(g, 1) for g in ids), file=sys.stderr)

